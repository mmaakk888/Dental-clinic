/** Deterministic SOURCE composition only. Never authenticates or deploys.
 * --write mechanically regenerates the candidate; default checks it. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n');
export function composeCloudReleaseRules(base, fragments) {
  const start = base.indexOf('    function commandValid(d) {');
  const end = base.indexOf('    function coupledIntent(', start);
  const terminal = '    match /{document=**} { allow read, write: if false; }';
  if (start < 0 || end <= start || base.split(terminal).length !== 2
    || /function (?:pr_preparedProsthetic|ex_preparedExpense|st_preparedSettings)\(/.test(base)) throw new Error('Expected unchanged reviewed base');
  const command = base.slice(start, end);
  if (!/: false;\s*}\s*$/.test(command)) throw new Error('Unknown command-dispatch layout');
  const next = command.replace(/: false;(\s*}\s*)$/, (_, close) =>
    ": d.kind == 'prosthetic' ? d.command.createdAt==d.createdAt && pr_preparedProsthetic(d.command)\n"
    + "        : d.kind == 'expense' ? d.command.createdAt==d.createdAt && ex_preparedExpense(d.command)\n"
    + "        : d.kind == 'settings' ? d.command.createdAt==d.createdAt && st_preparedSettings(d.command) : false;" + close);
  let result = base.slice(0, start) + next + base.slice(end);
  for (const [clinical, prosthetic, operation] of [
    ['clinicalAccountWrite(resource,request.resource.data,id)', 'pr_patientAccountWrite(resource,request.resource.data,id)', 'request.resource.data.lastOperationId'],
    ['clinicalSessionWrite(resource,request.resource.data,id)', 'pr_patientSessionWrite(resource,request.resource.data,id)', 'request.resource.data.lastOperationId'],
    ['clinicalCash(request.resource.data,id)', 'pr_patientCash(request.resource.data,id)', 'id'],
  ]) {
    if (result.split(clinical).length !== 2) throw new Error('Unknown clinical companion hook');
    result = result.replace(clinical, () => `(getAfter(intentPath(${operation})).data.kind=='prosthetic'?${prosthetic}:${clinical})`);
  }
  for (const [kind, source] of Object.entries(fragments)) {
    const helper = { prosthetic: 'pr_preparedProsthetic', expense: 'ex_preparedExpense', settings: 'st_preparedSettings' }[kind];
    if (!helper || !source.includes(`function ${helper}(`) || source.includes('rules_version')
      || source.includes('match /{document=**}')) throw new Error('Invalid domain fragment');
  }
  if (Object.keys(fragments).sort().join(',') !== 'expense,prosthetic,settings') throw new Error('Missing domain fragment');
  // Callback is essential: Rules regex strings may contain $', which is a
  // special JavaScript replacement-string token and would corrupt the source.
  result = result.replace(terminal, () => `${fragments.prosthetic}\n${fragments.expense}\n${fragments.settings}\n${terminal}`);
  result = '// Generated by scripts/build-cloud-release-rules.mjs; candidate, NOT a deployment.\n' + result;
  if (new TextEncoder().encode(result).byteLength > 256 * 1024) throw new Error('Rules source exceeds published size bound');
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--write') || args.length > 1) throw new Error('Only --write is supported');
  const result = composeCloudReleaseRules(read('rules/base.release.rules'), {
    prosthetic: read('rules/prosthetic.release.rules.fragment'),
    expense: read('rules/expense.release.rules.fragment'),
    settings: read('rules/settings.release.rules.fragment'),
  });
  if (args.includes('--write')) writeFileSync(resolve(root, 'firestore.release.rules'), result);
  else if (read('firestore.release.rules') !== result) throw new Error('Candidate has not been regenerated from these fragments');
  process.stdout.write(`Rules source ${args.includes('--write') ? 'regenerated' : 'matches'} (${Buffer.byteLength(result)} bytes); no live changes.\n`);
}
